import streamlit as st
import joblib
import os

# Configuración de la página
st.set_page_config(
    page_title="Human or Machine? Detector",
    page_icon="🤖",
    layout="centered"
)

st.title("🤖 Human or Machine? Detector")
st.write("Enter a text below to analyze whether it was written by a human or generated by Artificial Intelligence.")

# Función para cargar el modelo
@st.cache_resource
def load_model():
    # Ajusta esta ruta si tu modelo guardado tiene otro nombre o ubicación
    model_path = "app/models/baseline_tfidf_logreg.pkl" 
    if os.path.exists(model_path):
        return joblib.load(model_path)
    return None

model = load_model()

# Caja de texto de entrada para el usuario
user_input = st.text_area("Text to analyze:", placeholder="Type or paste your text here...")

if st.button("Analyze Text"):
    if user_input.strip() == "":
        st.warning("Please enter a valid text before analyzing.")
    elif model is None:
        st.error("Trained model file not found. Please verify the file path in the folder.")
    else:
        with st.spinner("Analyzing text patterns..."):
            
            # --- AQUÍ APLICAS LA PREDICCIÓN CON TU MODELO REAL ---
            prediction = model.predict([user_input])[0]
            
            # Opcional: si quieren mostrar confianza/probabilidad
            # prob = model.predict_proba([user_input])[0].max() * 100
            
            # Mapeo del resultado
            if prediction == 1 or prediction == "AI":
                result = "🤖 AI-Generated"
                st.success("Analysis completed!")
                st.error(result)
            else:
                result = "👤 Human-Written"
                st.success("Analysis completed!")
                st.info(result)

# Nota al pie
st.markdown("---")
st.caption('Developed for the "Human or Machine?" challenge · Neural Networks and Deep Learning')